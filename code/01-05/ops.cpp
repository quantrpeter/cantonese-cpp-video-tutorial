#include <iostream>

int main() {
    std::cout << 7 + 2 << '\n';
    std::cout << 7 - 2 << '\n';
    std::cout << 7 * 2 << '\n';
    std::cout << 7 / 2 << '\n';
    std::cout << 7 % 2 << '\n';
    std::cout << 7.0 / 2 << '\n';
    std::cout << 2 + 3 * 4 << '\n';
    std::cout << (2 + 3) * 4 << '\n';
}
